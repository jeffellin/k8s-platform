#!/usr/bin/env python3
"""Render clusters.yaml -> clusters/<name>/{kustomization,resourceset}.yaml, secrets/<app>/{kustomization,namespace}.yaml and .sops.yaml.

Flux syncs clusters/<name>/ ; the ResourceSets in it expand into one Flux Kustomization per
enabled app (and one '<app>-secrets' Kustomization for apps whose meta.yaml sets secrets: true).
Run with --check in CI to fail when committed output is stale.
"""
import sys, pathlib, yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
cfg = yaml.safe_load((ROOT / "clusters.yaml").read_text())

def meta(app):
    p = ROOT / "apps" / app / "meta.yaml"
    if not p.exists():
        sys.exit(f"unknown app '{app}': apps/{app}/meta.yaml not found")
    return yaml.safe_load(p.read_text()) or {}

APP_TMPL = """\
- apiVersion: kustomize.toolkit.fluxcd.io/v1
  kind: Kustomization
  metadata:
    name: << inputs.name >>
    namespace: flux-system
  spec:
    interval: 10m
    retryInterval: 1m
    timeout: 10m
    prune: true
    wait: true
    path: ./apps/<< inputs.name >>
    sourceRef: {kind: GitRepository, name: flux-system}
    dependsOn: << inputs.dependsOn | toJson >>
    postBuild:
      substitute: << inputs.vars | toJson >>
"""
SEC_TMPL = """\
- apiVersion: kustomize.toolkit.fluxcd.io/v1
  kind: Kustomization
  metadata:
    name: << inputs.name >>-secrets
    namespace: flux-system
  spec:
    interval: 10m
    prune: true
    wait: true
    path: ./clusters/<< inputs.cluster >>/secrets/<< inputs.name >>
    sourceRef: {kind: GitRepository, name: flux-system}
    decryption: {provider: sops, secretRef: {name: sops-age}}
"""

def resourceset(name, inputs, tmpl):
    rs = {
        "apiVersion": "fluxcd.controlplane.io/v1", "kind": "ResourceSet",
        "metadata": {"name": name, "namespace": "flux-system"},
        "spec": {"inputs": inputs, "resourcesTemplate": tmpl},
    }
    return rs

class Lit(str): pass
yaml.add_representer(Lit, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))

out = {}
errors = []
def pub(name):
    p = ROOT / "keys" / f"{name}.pub"
    if not p.exists():
        errors.append(f"missing keys/{name}.pub -- run hack/new-cluster.sh {name}" if name != "admin" else "missing keys/admin.pub -- run hack/new-cluster.sh <cluster>")
        return "MISSING"
    return p.read_text().strip()
sops_rules = []
for cname, c in cfg["clusters"].items():
    sops_rules.append({"path_regex": f"clusters/{cname}/secrets/.*\\.sops\\.yaml$", "encrypted_regex": "^(data|stringData)$",
                       "age": f"{pub('admin')},{pub(cname)}"})
out[ROOT / ".sops.yaml"] = ("# GENERATED by hack/render.py from keys/*.pub -- do not edit\n"
    "# Each secret is encrypted to admin + that cluster.\n" + yaml.dump({"creation_rules": sops_rules}, sort_keys=False))
for cname, c in cfg["clusters"].items():
    base = {**cfg.get("defaults", {}), **c.get("vars", {})}
    apps, secs = [], []
    for a in c["apps"]:
        a = {"name": a} if isinstance(a, str) else a
        m = meta(a["name"])
        deps = list(m.get("dependsOn", []))
        if m.get("secrets"):
            deps.append(f"{a['name']}-secrets")
            secs.append({"name": a["name"], "cluster": cname})
            sdir = ROOT / "clusters" / cname / "secrets" / a["name"]
            for f in m["secrets"]:
                fp = sdir / f
                if not fp.exists():
                    errors.append(f"missing secret {fp.relative_to(ROOT)} (app '{a['name']}'; see docs/secrets.md)")
                elif "\nsops:" not in "\n" + fp.read_text():
                    errors.append(f"NOT ENCRYPTED: {fp.relative_to(ROOT)} -- run: sops --encrypt --in-place {fp.relative_to(ROOT)}")
            ns = m.get("namespace", a["name"])
            out[sdir / "namespace.yaml"] = f"# GENERATED by hack/render.py\napiVersion: v1\nkind: Namespace\nmetadata: {{name: {ns}}}\n"
            out[sdir / "kustomization.yaml"] = ("# GENERATED by hack/render.py\napiVersion: kustomize.config.k8s.io/v1beta1\n"
                "kind: Kustomization\nresources:\n  - namespace.yaml\n" + "".join(f"  - {f}\n" for f in m["secrets"]))
        enabled = {x["name"] if isinstance(x, dict) else x for x in c["apps"]}
        missing = [d for d in m.get("dependsOn", []) if d not in enabled]
        if missing:
            sys.exit(f"{cname}: app '{a['name']}' requires {missing} (apps/{a['name']}/meta.yaml)")
        vars_ = {k: str(v) for k, v in {**base, **a.get("options", {})}.items()}
        apps.append({"name": a["name"], "dependsOn": [{"name": d} for d in deps], "vars": vars_})
    docs = [resourceset("apps", apps, Lit(APP_TMPL))]
    if secs:
        docs.append(resourceset("app-secrets", secs, Lit(SEC_TMPL)))
    body = "# GENERATED by hack/render.py from clusters.yaml -- do not edit\n" + \
           "---\n".join(yaml.dump(d, sort_keys=False) for d in docs)
    out[ROOT / "clusters" / cname / "resourceset.yaml"] = body
    out[ROOT / "clusters" / cname / "kustomization.yaml"] = (
        "# GENERATED by hack/render.py\napiVersion: kustomize.config.k8s.io/v1beta1\n"
        "kind: Kustomization\nresources: [resourceset.yaml]\n")

if errors:
    print("\n".join("error: " + e for e in errors)); sys.exit(1)
stale = False
for p, body in out.items():
    if "--check" in sys.argv:
        if not p.exists() or p.read_text() != body:
            print("stale:", p.relative_to(ROOT)); stale = True
    else:
        p.parent.mkdir(parents=True, exist_ok=True); p.write_text(body)
        print("wrote", p.relative_to(ROOT))
sys.exit(1 if stale else 0)
